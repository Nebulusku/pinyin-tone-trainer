/* Connects the app to your Supabase project. Run from the app folder:  node tools/set-supabase.js
   Asks for the Project URL and the publishable (anon) key — both are meant to be public; the
   database is protected by row-level security (tools/supabase-setup.sql).
   Writes supabase-config.js, removes the old login.js hash, then commits and pushes. */
const fs = require("fs"), path = require("path"), readline = require("readline");
const { execFileSync } = require("child_process");

const root = path.join(__dirname, "..");
const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const ask = q => new Promise(r => rl.question(q, a => r(a.trim())));

(async () => {
  const url = (await ask("Supabase Project URL (https://xxxx.supabase.co): ")).replace(/\/+$/, "");
  const anonKey = await ask("Publishable / anon key: ");
  rl.close();
  if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) { console.error("That doesn't look like a Supabase project URL."); process.exit(1); }
  if (/^sb_secret_/.test(anonKey) || /service_role/.test(Buffer.from(anonKey.split(".")[1] || "", "base64").toString())) {
    console.error("That's the SECRET key — never publish it. Use the publishable (anon) key instead.");
    process.exit(1);
  }
  if (anonKey.length < 20) { console.error("That key looks too short."); process.exit(1); }

  const r = await fetch(`${url}/auth/v1/settings`, { headers: { apikey: anonKey } }).catch(() => null);
  if (!r || !r.ok) { console.error(`Couldn't reach the project with that key (${r ? "HTTP " + r.status : "network error"}).`); process.exit(1); }
  const settings = await r.json();
  if (!settings.disable_signup) console.warn("⚠ Sign-ups are still open — turn off 'Allow new users to sign up' in Supabase → Authentication.");

  fs.writeFileSync(path.join(root, "supabase-config.js"),
    `/* Generated by tools/set-supabase.js — public project URL + publishable key (data is protected by row-level security). */\nvar SUPABASE = ${JSON.stringify({ url, anonKey })};\n`);
  console.log("Saved supabase-config.js");
  if (process.argv.includes("--no-push")) return;
  try {
    if (fs.existsSync(path.join(root, "login.js"))) execFileSync("git", ["rm", "-q", "login.js"], { cwd: root, stdio: "inherit" });
    execFileSync("git", ["add", "supabase-config.js"], { cwd: root, stdio: "inherit" });
    execFileSync("git", ["commit", "-q", "-m", "Connect cloud login + sync (Supabase)"], { cwd: root, stdio: "inherit" });
    execFileSync("git", ["push", "-q"], { cwd: root, stdio: "inherit" });
    console.log("Published — sign in with your Supabase email + password (allow ~1 minute for GitHub Pages).");
  } catch (e) {
    console.error("Saved locally, but publishing failed — run: git add -A && git commit -m supabase && git push");
  }
})();
